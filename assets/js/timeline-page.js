/* Wave 22: Legends Timeline page logic.
   Era filter + year-rail keyboard navigation for timeline.html.
   Content itself is static (generated by scripts/build_timeline.py) so the
   page works with JS disabled; this module only enhances it. */

export const YEARS = Array.from({ length: 25 }, (_, i) => 2002 + i);

/* Era of a timeline year. */
export function eraOfYear(year) {
  return year <= 2006 ? "toybiz" : "hasbro";
}

/* Years visible under an era filter value ("all" | "toybiz" | "hasbro"). */
export function visibleYears(era) {
  if (era !== "toybiz" && era !== "hasbro") return YEARS.slice();
  return YEARS.filter((y) => eraOfYear(y) === era);
}

/* Rail keyboard math: given the focused link index, a key, and the list of
   currently-visible link indexes, return the next focus index (or null). */
export function railStep(currentIdx, key, visibleIdx) {
  const pos = visibleIdx.indexOf(currentIdx);
  if (pos === -1) return null;
  const n = visibleIdx.length;
  if (key === "ArrowRight" || key === "ArrowDown") return visibleIdx[(pos + 1) % n];
  if (key === "ArrowLeft" || key === "ArrowUp") return visibleIdx[(pos - 1 + n) % n];
  if (key === "Home") return visibleIdx[0];
  if (key === "End") return visibleIdx[n - 1];
  return null;
}

/* Browser wiring. No-op when the timeline page markup is absent. */
export function initTimelinePage() {
  if (typeof document === "undefined") return;
  const rail = document.getElementById("tl-rail");
  const sections = Array.from(document.querySelectorAll(".tl-year"));
  if (!rail || sections.length === 0) return;

  const links = Array.from(rail.querySelectorAll("a"));
  const linkYear = (a) => parseInt(a.getAttribute("href").slice(6), 10);

  const applyEra = (era) => {
    const keep = new Set(visibleYears(era));
    for (const s of sections) {
      const y = parseInt(s.id.slice(5), 10);
      s.hidden = !keep.has(y);
    }
    for (const a of links) {
      const li = a.closest("li");
      if (li) li.hidden = !keep.has(linkYear(a));
    }
  };

  for (const r of document.querySelectorAll('input[name="tl-era"]')) {
    r.addEventListener("change", () => applyEra(r.value));
  }

  rail.addEventListener("keydown", (e) => {
    const visible = links
      .filter((a) => !a.closest("li").hidden)
      .map((a) => links.indexOf(a));
    const next = railStep(links.indexOf(document.activeElement), e.key, visible);
    if (next !== null && next !== undefined) {
      e.preventDefault();
      links[next].focus();
    }
  });
}

initTimelinePage();
